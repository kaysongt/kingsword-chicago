import {cp, mkdir, writeFile, readFile, readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const target=path.join(root,'docs');
await mkdir(target,{recursive:true});
await cp(path.join(root,'dist'),target,{recursive:true});
const hash=createHash('sha256');
for(const file of ['app.js','domain.mjs','styles.css','index.html','manifest.webmanifest','sw.js','assets/mark.svg','assets/icon-192.png','assets/icon-512.png'])hash.update(await readFile(path.join(root,'dist',file)));
const buildId=hash.digest('hex').slice(0,12);
const worker=await readFile(path.join(root,'dist/sw.js'),'utf8');
await writeFile(path.join(target,'sw.js'),worker.replace('__BUILD_ID__',buildId));
await writeFile(path.join(target,'.nojekyll'),'');
console.log('GitHub Pages build ready: docs/ (publish main branch, /docs folder)');
